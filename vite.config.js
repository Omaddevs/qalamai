import { defineConfig, loadEnv } from 'vite'
import react from '@vitejs/plugin-react'
import { LANGS } from './shared/i18n.js'
import i18nSplit from './scripts/vite-i18n-split.mjs'
import { PUBLIC_PAGES } from './src/landing/pages.js'
import landingMsg from './src/i18n/msg/landing.js'
import authMsg from './src/i18n/msg/auth.js'

const MSG = { ...landingMsg, ...authMsg }
const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;')

/**
 * SEO files that depend on the public domain (VITE_SITE_URL, default https://qalam.uz):
 *   - %SITE_URL% in index.html is replaced at build time;
 *   - /robots.txt and /sitemap.xml are emitted into dist/ and served by dev/preview.
 *   - every public page (src/landing/pages.js: /narxlar, /kirish …) gets its own prerendered
 *     HTML (dist/narxlar.html) with its own title, description and canonical, so search
 *     engines see separate pages and can show them as sitelinks under the main result.
 * Public Link-in-Bio pages have their own sitemap, generated by the API from the
 * database (/b/sitemap.xml), so it always matches what is published.
 */
function seo(siteUrl) {
  const home = `${siteUrl}/`
  const files = {
    'robots.txt': [
      'User-agent: *',
      'Allow: /',
      'Disallow: /api/',
      'Disallow: /b/*/l/',
      '',
      `Sitemap: ${siteUrl}/sitemap.xml`,
      `Sitemap: ${siteUrl}/b/sitemap.xml`,
      '',
    ].join('\n'),
    // The landing and the public pages (everything after "#/" is the app itself and is
    // invisible to search engines). Each language version has its own URL.
    'sitemap.xml': [
      '<?xml version="1.0" encoding="UTF-8"?>',
      '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
      `  <url><loc>${home}</loc><changefreq>weekly</changefreq><priority>1.0</priority></url>`,
      ...PUBLIC_PAGES.map((p) => `  <url><loc>${siteUrl}${p.path}</loc><changefreq>weekly</changefreq><priority>${p.auth ? '0.6' : '0.9'}</priority></url>`),
      ...LANGS.map((l) => `  <url><loc>${home}?lang=${l.id}</loc><changefreq>weekly</changefreq><priority>0.8</priority></url>`),
      '</urlset>',
      '',
    ].join('\n'),
  }
  const types = { 'robots.txt': 'text/plain; charset=utf-8', 'sitemap.xml': 'application/xml; charset=utf-8' }
  // Must not return anything: Vite treats a returned function as a post-middleware hook.
  const serve = (server) => {
    server.middlewares.use((req, res, next) => {
      const name = req.url?.split('?')[0].slice(1)
      if (!files[name]) return next()
      res.setHeader('Content-Type', types[name])
      res.end(files[name])
    })
  }
  // hreflang alternates: the same page in every language, the bare address for everyone else.
  const alternates = (url) =>
    [
      ...LANGS.map((l) => `<link rel="alternate" hreflang="${l.id === 'uz-cyrl' ? 'uz-Cyrl' : l.id}" href="${url}?lang=${l.id}" />`),
      `<link rel="alternate" hreflang="x-default" href="${url}" />`,
    ].join('\n    ')

  // Crawlable links to every public page, in the HTML itself (React replaces them once it runs).
  const staticNav = `<nav><a href="/">QalamAI</a>${PUBLIC_PAGES.map((p) => ` · <a href="${p.path}">${esc(MSG[p.title].uz.split(/ [—|] /)[0])}</a>`).join('')}</nav>`

  // index.html (already built) → the same page with another address, title and description (Uzbek;
  // the app switches them to the visitor's language). Each replacement must hit, or the build fails.
  const variant = (html, page) => {
    const url = `${siteUrl}${page.path}`
    const title = esc(MSG[page.title].uz)
    const desc = esc(MSG[page.desc].uz)
    const subs = [
      [/<title>[^<]*<\/title>/, `<title>${title}</title>`],
      [/(<meta name="description" content=")[^"]*/, `$1${desc}`],
      [/(<link rel="canonical" href=")[^"]*/, `$1${url}`],
      [/(<meta property="og:url" content=")[^"]*/, `$1${url}`],
      [/(<meta property="og:title" content=")[^"]*/, `$1${title}`],
      [/(<meta property="og:description" content=")[^"]*/, `$1${desc}`],
      [/(<meta name="twitter:title" content=")[^"]*/, `$1${title}`],
      [/(<meta name="twitter:description" content=")[^"]*/, `$1${desc}`],
      [/(<h1 id="seo-h1">)[^<]*/, `$1${title}`],
      [/(<p id="seo-p">)[^<]*/, `$1${desc}`],
    ]
    for (const [re, to] of subs) {
      if (!re.test(html)) throw new Error(`qalam-seo: ${re} not found in index.html`)
      html = html.replace(re, to)
    }
    return html.replace(alternates(home), alternates(url))
  }
  return {
    name: 'qalam-seo',
    transformIndexHtml: {
      order: 'pre', // before Vite parses the URLs in index.html
      handler: (html) => html.replaceAll('%SITE_URL%', siteUrl).replace('<!-- %HREFLANG% -->', alternates(home)).replace('<!-- %STATIC_NAV% -->', staticNav),
    },
    configureServer: serve,
    configurePreviewServer: serve,
    generateBundle: {
      order: 'post', // after Vite has written index.html into the bundle
      handler(_, bundle) {
        for (const [fileName, source] of Object.entries(files)) this.emitFile({ type: 'asset', fileName, source })
        const index = bundle['index.html']
        if (!index) return
        const html = String(index.source)
        for (const page of PUBLIC_PAGES) this.emitFile({ type: 'asset', fileName: `${page.path.slice(1)}.html`, source: variant(html, page) })
      },
    },
  }
}

// The Node API (server/) runs on :4000. In development the browser talks to /api on
// the Vite origin, so cookies are first-party and no CORS setup is needed.
export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), 'VITE_')
  const siteUrl = (env.VITE_SITE_URL || 'https://qalam.uz').replace(/\/+$/, '')
  const api = { target: process.env.API_TARGET ?? 'http://localhost:4000', changeOrigin: false }
  return {
    plugins: [react(), seo(siteUrl), i18nSplit(new URL('./src/i18n/msg', import.meta.url).pathname)],
    // Lazily imported heavy deps: pre-bundle them at start-up. Found only when a page first
    // imports them, Vite re-optimizes mid-session and answers the open page with
    // "504 Outdated Optimize Dep" — the PDF editor then fails with "PDF ni oçib bölmadi".
    optimizeDeps: { include: ['pdfjs-dist', 'mammoth/mammoth.browser.js'] },
    server: {
      proxy: {
        '/api': api,
        // public Link-in-Bio pages
        '/b/': api,
        // Google Search Console verification file (set in the admin panel)
        '^/google[0-9a-f]+\\.html$': api,
      },
    },
    preview: {
      proxy: {
        '/api': api,
        '/b/': api,
        '^/google[0-9a-f]+\\.html$': api,
      },
    },
  }
})
