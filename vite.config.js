import { defineConfig, loadEnv } from 'vite'
import react from '@vitejs/plugin-react'
import { DEFAULT_LANG, LANGS, dirOf, htmlLangOf, isLang, translate } from './shared/i18n.js'
import i18nSplit from './scripts/vite-i18n-split.mjs'
import { loadDict } from './scripts/i18n-dict.mjs'
import { ABOUT_PAGES, ALL_PAGES, INDEXABLE_PAGES, PRODUCT_PAGES, PUBLIC_PAGES, TOOL_PAGES, parentsOf, relatedTools } from './src/landing/pages.js'
import { alternatesOf, faqOf, langsOf, ogLocaleOf, pageJsonLd, pageTexts, pageUrl, productContent } from './src/landing/seo-meta.js'

const MSG_DIR = new URL('./src/i18n/msg', import.meta.url).pathname
const LOCALES_DIR = new URL('./src/i18n/locales', import.meta.url).pathname
// every UI dictionary (src/i18n/msg/*.js + locales/<lang>/*.json): the prerendered pages speak each language
const { dict: MSG } = await loadDict(MSG_DIR, LOCALES_DIR)
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const ROBOTS_INDEX = 'index, follow, max-image-preview:large'

/**
 * SEO files that depend on the public domain (VITE_SITE_URL, default https://qalamai.uz):
 *   - %SITE_URL% in index.html is replaced at build time;
 *   - /robots.txt and /sitemap.xml are emitted into dist/ and served by dev/preview;
 *   - every public page (src/landing/pages.js: /narxlar, /vositalar/pdf-dan-word …) gets its own
 *     prerendered HTML in every language — dist/narxlar.html (Uzbek, the bare address) and
 *     dist/narxlar.ru.html (/narxlar?lang=ru, picked by nginx) — with its own <html lang>, title,
 *     description, canonical, hreflang, JSON-LD and readable content, so crawlers that don't run
 *     JavaScript see the real page; dist/404.html is what nginx answers unknown addresses with.
 * Public Link-in-Bio pages have their own sitemap, generated by the API from the
 * database (/b/sitemap.xml), so it always matches what is published.
 */
function seo(siteUrl) {
  const files = {
    'robots.txt': [
      'User-agent: *',
      'Allow: /',
      'Disallow: /api/',
      'Disallow: /b/*/l/',
      '',
      `Sitemap: ${siteUrl}/sitemap.xml`,
      `Sitemap: ${siteUrl}/b/sitemap.xml`,
      `Sitemap: ${siteUrl}/yangiliklar/sitemap.xml`,
      '',
    ].join('\n'),
    // Indexable public pages in every language, each with its alternates. The app itself (after
    // "#/"), sign-in / sign-up and shared presentations are not listed (they are noindex).
    'sitemap.xml': [
      '<?xml version="1.0" encoding="UTF-8"?>',
      '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">',
      ...[null, ...INDEXABLE_PAGES].flatMap((page) => {
        const path = page?.path ?? '/'
        const langs = langsOf(page)
        const alts = alternatesOf(siteUrl, path, langs).map((a) => `    <xhtml:link rel="alternate" hreflang="${a.hreflang}" href="${esc(a.href)}"/>`)
        return langs.map((id) => ['  <url>', `    <loc>${esc(pageUrl(siteUrl, path, id))}</loc>`, ...alts, '  </url>'].join('\n'))
      }),
      '</urlset>',
      '',
    ].join('\n'),
  }
  const types = { 'robots.txt': 'text/plain; charset=utf-8', 'sitemap.xml': 'application/xml; charset=utf-8' }
  // Must not return anything: Vite treats a returned function as a post-middleware hook.
  const serve = (server) => {
    server.middlewares.use((req, res, next) => {
      const name = req.url?.split('?')[0].slice(1)
      if (!files[name]) return next()
      res.setHeader('Content-Type', types[name])
      res.end(files[name])
    })
  }

  /** What crawlers read before the app starts (React replaces it): the page's real content and links. */
  function staticBody(page, lang, tr, texts) {
    const href = (path) => esc(lang === DEFAULT_LANG ? path : `${path}?lang=${lang}`)
    const a = (path, label) => `<a href="${href(path)}">${esc(label)}</a>`
    const out = [`<h1>${esc(texts.h1)}</h1>`, `<p>${esc(page?.toolPage || page?.productPage ? texts.lead : texts.desc)}</p>`]
    if (page?.productPage) {
      const c = productContent(page, tr, lang)
      out.push(`<p>${esc(c.price)}</p>`)
      out.push(`<h2>${esc(c.label('how'))}</h2><ol>${c.steps.map((x) => `<li>${esc(x)}</li>`).join('')}</ol>`)
      out.push(`<h2>${esc(c.label('incl'))}</h2><ul>${c.incl.map((x) => `<li>${esc(x)}</li>`).join('')}</ul>`)
      out.push(`<h2>${esc(c.label('faq'))}</h2>`, ...c.faq.map(([q, ans]) => `<h3>${esc(q)}</h3><p>${esc(ans)}</p>`))
    }
    if (page?.id === 'faq') out.push(...faqOf(tr).map(([q, ans]) => `<h2>${esc(q)}</h2><p>${esc(ans)}</p>`))
    const toolList = (list) => `<ul>${list.map((p) => { const x = pageTexts(p, tr, lang); return `<li>${a(p.path, x.name)} — ${esc(x.lead)}</li>` }).join('')}</ul>`
    if (page?.id === 'tools') {
      for (const cat of ['pdf', 'edit', 'image', 'document']) out.push(`<h2>${esc(tr(`fs.cat.${cat}`))}</h2>`, toolList(TOOL_PAGES.filter((p) => p.category === cat)))
    }
    if (page?.toolPage) {
      out.push(`<h2>${esc(tr('seo.tool.how'))}</h2><ol>${[1, 2, 3].map((n) => `<li>${esc(tr(`seo.tool.step${n}`))}</li>`).join('')}</ol>`)
      out.push(`<h2>${esc(tr('seo.tool.related'))}</h2>`, toolList(relatedTools(page)))
    }
    // product pages exist only in the regional languages: linked from those versions only
    const navPages = [...PUBLIC_PAGES, ...PRODUCT_PAGES, ...ABOUT_PAGES].filter((p) => langsOf(p).includes(lang))
    const nav = [['/', 'QalamAI'], ...navPages.map((p) => [p.path, pageTexts(p, tr, lang).h1])]
    out.push(`<nav>${nav.map(([p, l]) => a(p, l)).join(' · ')}</nav>`)
    return out.join('\n      ')
  }

  /**
   * index.html → one page in one language. page null = home, '404' = the not-found page.
   * Every replacement must hit, or the build fails (index.html changed shape).
   */
  function render(html, page, lang) {
    const tr = (key, vars) => translate(MSG, key, vars, lang)
    const notFound = page === '404'
    const p = notFound ? null : page
    const texts = notFound ? { title: `404 — ${tr('nf.title')} · QalamAI`, desc: tr('nf.text'), h1: tr('nf.title') } : pageTexts(p, tr, lang)
    const path = p?.path ?? '/'
    const url = pageUrl(siteUrl, path, lang)
    const indexable = !notFound && !p?.noindex
    const robots = notFound ? 'noindex' : indexable ? ROBOTS_INDEX : 'noindex, follow'
    const title = esc(texts.title)
    const desc = esc(texts.desc)
    const ld = indexable ? pageJsonLd({ site: siteUrl, page: p, lang, tr, parents: parentsOf(p) }) : null
    const subs = [
      [/<html lang="[^"]*">/, `<html lang="${htmlLangOf(lang)}"${dirOf(lang) === 'rtl' ? ' dir="rtl"' : ''}>`],
      [/<title>[^<]*<\/title>/, `<title>${title}</title>`],
      [/(<meta name="description" content=")[^"]*/, `$1${desc}`],
      [/(<meta name="robots" content=")[^"]*/, `$1${robots}`],
      [/\s*<link rel="canonical" href="[^"]*" \/>/, indexable ? `\n    <link rel="canonical" href="${esc(url)}" />` : ''],
      [/\s*<!-- %HREFLANG% -->/, indexable ? alternatesOf(siteUrl, path, langsOf(p)).map((x) => `\n    <link rel="alternate" hreflang="${x.hreflang}" href="${esc(x.href)}" />`).join('') : ''],
      [/(<meta property="og:locale" content=")[^"]*/, `$1${ogLocaleOf(lang)}`],
      [/\s*<meta property="og:url" content="[^"]*" \/>/, notFound ? '' : `\n    <meta property="og:url" content="${esc(url)}" />`],
      [/(<meta property="og:title" content=")[^"]*/, `$1${title}`],
      [/(<meta property="og:description" content=")[^"]*/, `$1${desc}`],
      [/(<meta property="og:image:alt" content=")[^"]*/, `$1${title}`],
      [/(<meta name="twitter:title" content=")[^"]*/, `$1${title}`],
      [/(<meta name="twitter:description" content=")[^"]*/, `$1${desc}`],
      [/<!-- %PAGE_LD% -->/, ld ? `<script type="application/ld+json" id="seo-page-ld">${JSON.stringify(ld).replace(/</g, '\\u003c')}</script>` : ''],
      [/<!-- %STATIC% -->/, staticBody(p, lang, tr, texts)],
    ]
    for (const [re, to] of subs) {
      if (!re.test(html)) throw new Error(`qalam-seo: ${re} not found in index.html`)
      html = html.replace(re, to)
    }
    return html
  }

  /** dist file of a page in a language: index.html, index.ru.html, narxlar.html, vositalar/pdf-dan-word.kk.html … */
  const fileOf = (page, lang) => `${page ? page.path.slice(1) : 'index'}${lang === DEFAULT_LANG ? '' : `.${lang}`}.html`

  // Two plugins: one hook each (transformIndexHtml takes a single handler).
  const devPage = {
    name: 'qalam-seo-dev',
    apply: 'serve',
    transformIndexHtml: {
      // dev server: the page and language the address asks for, as production would serve it
      order: 'post',
      handler(html, ctx) {
        const u = new URL(ctx.originalUrl ?? '/', 'http://x')
        const known = ['/', '/index.html'].includes(u.pathname) ? null : ALL_PAGES.find((p) => p.path === u.pathname.replace(/\/+$/, ''))
        // /admin and shared presentations (/v/<id>) are app screens, served the plain index.html
        const page = known === undefined && !/^\/(admin|v\/)/.test(u.pathname) ? '404' : known ?? null
        const l = u.searchParams.get('lang')
        return render(html, page, l && isLang(l) && !known?.noindex && langsOf(known).includes(l) ? l : DEFAULT_LANG)
      },
    },
  }
  return [devPage, {
    name: 'qalam-seo',
    transformIndexHtml: {
      order: 'pre', // before Vite parses the URLs in index.html
      handler: (html) => html.replaceAll('%SITE_URL%', siteUrl),
    },
    configureServer: serve,
    configurePreviewServer: serve,
    generateBundle: {
      order: 'post', // after Vite has written index.html into the bundle
      handler(_, bundle) {
        for (const [fileName, source] of Object.entries(files)) this.emitFile({ type: 'asset', fileName, source })
        const index = bundle['index.html']
        if (!index) return
        const html = String(index.source)
        for (const lang of LANGS.map((l) => l.id)) {
          for (const page of [null, ...ALL_PAGES]) {
            if (page?.noindex && lang !== DEFAULT_LANG) continue // forms: one Uzbek file, the app switches language itself
            if (!langsOf(page).includes(lang)) continue // product pages: regional languages only (nginx serves the Uzbek file)
            const source = render(html, page, lang)
            const fileName = fileOf(page, lang)
            if (fileName === 'index.html') index.source = source
            else this.emitFile({ type: 'asset', fileName, source })
          }
        }
        this.emitFile({ type: 'asset', fileName: '404.html', source: render(html, '404', DEFAULT_LANG) })
      },
    },
  }]
}

// The Node API (server/) runs on :4000. In development the browser talks to /api on
// the Vite origin, so cookies are first-party and no CORS setup is needed.
export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), 'VITE_')
  const siteUrl = (env.VITE_SITE_URL || 'https://qalamai.uz').replace(/\/+$/, '')
  const api = { target: process.env.API_TARGET ?? 'http://localhost:4000', changeOrigin: false }
  return {
    plugins: [react(), seo(siteUrl), i18nSplit(MSG_DIR, LOCALES_DIR)],
    // the public address, for canonical / hreflang links written by the app (src/seo.js)
    define: { __SITE_URL__: JSON.stringify(siteUrl) },
    // Lazily imported heavy deps: pre-bundle them at start-up. Found only when a page first
    // imports them, Vite re-optimizes mid-session and answers the open page with
    // "504 Outdated Optimize Dep" — the PDF editor then fails with "PDF ni oçib bölmadi".
    optimizeDeps: {
      include: ['pdfjs-dist', 'pdfjs-dist/build/pdf.worker.mjs', 'mammoth/mammoth.browser.js', 'pdf-lib', '@pdf-lib/fontkit', 'fflate', 'zod', 'docx', 'exceljs', 'pptxgenjs', 'node-html-parser'],
      exclude: ['onnxruntime-web'], // loads its own .wasm
    },
    // The file tools run in the browser with the server's own code (server/src/converters/core):
    // its imports must resolve to this app's copies, not to server/node_modules.
    resolve: { dedupe: ['pdf-lib', '@pdf-lib/fontkit', 'fflate', 'zod', 'docx', 'exceljs', 'pptxgenjs', 'node-html-parser', 'pdfjs-dist', 'mammoth'] },
    // the tool worker lazy-loads each tool, which needs an ES-module worker
    worker: { format: 'es' },
    server: {
      proxy: {
        '/api': api,
        // public Link-in-Bio pages
        '/b/': api,
        // Google Search Console verification file (set in the admin panel)
        '^/google[0-9a-f]+\\.html$': api,
        // news sitemap, made by the API from the database
        '^/yangiliklar/sitemap\\.xml$': api,
      },
    },
    preview: {
      proxy: {
        '/api': api,
        '/b/': api,
        '^/google[0-9a-f]+\\.html$': api,
        // news sitemap, made by the API from the database
        '^/yangiliklar/sitemap\\.xml$': api,
      },
    },
  }
})
