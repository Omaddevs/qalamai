// Builds shared/bio-icons.js — SVG paths (Phosphor Icons, MIT) for the Link-in-Bio renderer,
// which runs both in the browser (live preview) and on the server (public page), so it cannot
// use the React icon components. Run: node scripts/build-bio-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const NAMES = {
  telegram: 'TelegramLogo', instagram: 'InstagramLogo', youtube: 'YoutubeLogo', tiktok: 'TiktokLogo', facebook: 'FacebookLogo',
  linkedin: 'LinkedinLogo', x: 'XLogo', email: 'Envelope', phone: 'Phone', website: 'Globe', whatsapp: 'WhatsappLogo',
  github: 'GithubLogo', threads: 'ThreadsLogo', pinterest: 'PinterestLogo', spotify: 'SpotifyLogo', twitch: 'TwitchLogo',
  discord: 'DiscordLogo', behance: 'BehanceLogo', dribbble: 'DribbbleLogo',
  link: 'LinkSimple', arrow: 'ArrowUpRight', arrowRight: 'ArrowRight', caret: 'CaretRight', star: 'Star', sparkle: 'Sparkle',
  calendar: 'CalendarBlank', file: 'FileText', images: 'Images', pin: 'MapPin', chat: 'ChatCircleDots', heart: 'Heart',
  gift: 'Gift', leaf: 'Leaf', barbell: 'Barbell', person: 'PersonSimpleRun', rocket: 'RocketLaunch', book: 'BookOpen',
  play: 'PlayCircle', users: 'UsersThree', chart: 'ChartLineUp', trophy: 'Trophy', bag: 'ShoppingBag', briefcase: 'Briefcase',
  palette: 'Palette', music: 'MusicNotes', camera: 'Camera', coffee: 'Coffee', crown: 'Crown', lightbulb: 'Lightbulb',
  info: 'Info', user: 'User', grid: 'SquaresFour', bell: 'Bell', check: 'SealCheck', dots: 'DotsThree', menu: 'List',
  close: 'X', smiley: 'Smiley', flower: 'Flower', scissors: 'Scissors', paint: 'PaintBrush', video: 'VideoCamera',
  microphone: 'Microphone', pen: 'PenNib', home: 'House', clock: 'Clock', shield: 'ShieldCheck', money: 'CurrencyCircleDollar',
}

const out = {}
for (const [key, comp] of Object.entries(NAMES)) {
  const src = readFileSync(new URL(`../node_modules/@phosphor-icons/react/dist/defs/${comp}.mjs`, import.meta.url), 'utf8')
  const pick = (weight) => {
    const block = src.split(`"${weight}",`)[1]?.split(/\n  \],?\n/)[0] ?? ''
    // drop the faded duotone layers (opacity) — single-colour icons only
    return [...block.matchAll(/d: "([^"]+)"(?:,\s*opacity)?/g)].filter((m) => !m[0].includes('opacity')).map((m) => m[1])
  }
  out[key] = { regular: pick('regular'), fill: pick('fill') }
  if (!out[key].regular.length) throw new Error(`no paths for ${comp}`)
}
writeFileSync(
  new URL('../shared/bio-icons.js', import.meta.url),
  `// Generated by scripts/build-bio-icons.mjs — do not edit.\n// Phosphor Icons (regular + fill), MIT License — https://phosphoricons.com\nexport const BIO_ICONS = ${JSON.stringify(out)}\n`,
)
console.log(Object.keys(out).length, 'icons')
